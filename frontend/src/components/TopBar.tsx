import { FlaskConical, Loader2, PlayCircle, X } from "lucide-react";
import { useApp, type View } from "../lib/store";

const TABS: { id: View; label: string }[] = [
  { id: "twin", label: "Digital twin" },
  { id: "energy", label: "Energy balance" },
  { id: "investigate", label: "Investigate" },
  { id: "evaluation", label: "Model evaluation" },
  { id: "sources", label: "Sources and limits" },
];

export function TopBar({ onStartDemo }: { onStartDemo: () => void }) {
  const view = useApp((s) => s.view);
  const setView = useApp((s) => s.setView);
  const busy = useApp((s) => s.busy);
  const error = useApp((s) => s.error);
  const setError = useApp((s) => s.setError);
  return (
    <header className="relative flex h-14 shrink-0 items-center gap-6 border-b border-hair bg-panel px-4">
      <div className="flex items-baseline gap-2">
        <span className="font-cond text-[19px] font-semibold tracking-tight">Sharavathi GridWatch</span>
        <span className="hidden text-[12px] text-ink-3 xl:inline">grid digital twin for energy-imbalance screening</span>
      </div>
      <nav className="flex h-full items-stretch gap-1" aria-label="Views">
        {TABS.map((t) => (
          <button key={t.id} onClick={() => setView(t.id)} aria-current={view === t.id ? "page" : undefined}
            className={`relative px-3 font-cond text-[14px] ${view === t.id ? "text-ink" : "text-ink-3 hover:text-ink-2"}`}>
            {t.label}
            {view === t.id && <span className="absolute inset-x-2 bottom-0 h-[2px] rounded-t bg-flow" />}
          </button>
        ))}
      </nav>
      <div className="ml-auto flex items-center gap-3">
        {busy && <span className="flex items-center gap-1.5 text-[12px] text-ink-2"><Loader2 size={14} className="animate-spin" />{busy}</span>}
        <span className="flex items-center gap-1.5 rounded border border-truth/60 px-2 py-1 text-[12px] text-ink" title="All measurements are generated by the simulator; the network is an illustrative model">
          <FlaskConical size={13} color="var(--color-truth)" /> Simulated data, illustrative network
        </span>
        <button onClick={onStartDemo} className="flex items-center gap-1.5 rounded border border-flow px-3 py-1.5 font-cond text-[14px] font-semibold text-ink hover:bg-flow/15">
          <PlayCircle size={15} /> Start demo
        </button>
      </div>
      {error && (
        <div role="alert" className="absolute right-4 top-16 z-50 flex max-w-md items-start gap-2 rounded border border-alert/60 bg-panel px-3 py-2 text-[12.5px] shadow-xl">
          <span className="text-ink">{error}</span>
          <button aria-label="Dismiss" onClick={() => setError(null)} className="text-ink-3 hover:text-ink"><X size={14} /></button>
        </div>
      )}
    </header>
  );
}
