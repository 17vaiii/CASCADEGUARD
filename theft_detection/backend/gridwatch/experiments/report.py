"""Render results.json as a Markdown report (no numbers are typed by hand)."""

from __future__ import annotations

from pathlib import Path


def _f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def _ci(r, k):
    ci = (r.get("ci95") or {}).get(k)
    return f"{_f(r.get(k))} [{_f(ci[0])}, {_f(ci[1])}]" if ci else _f(r.get(k))


def _main_table(rows):
    out = ["| Method | Signals | Threshold | Precision | Recall | F1 [95% CI] | FPR | ROC-AUC | PR-AUC [95% CI] |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['name']} | {r['signals']} | {_f(r['threshold'])} | {_f(r['precision'])} | {_f(r['recall'])} "
                   f"| {_ci(r, 'f1')} | {_f(r['fpr'], 4)} | {_f(r['roc_auc'])} | {_ci(r, 'pr_auc')} |")
    return "\n".join(out)


def _sweep_table(sw, level, metric):
    levels = sw["levels"]
    out = ["| Method | " + " | ".join(str(lv) for lv in levels) + " |", "|---|" + "---|" * len(levels)]
    for m, rows in sw[level].items():
        out.append(f"| {m} | " + " | ".join(_f(r[metric]) for r in rows) + " |")
    return "\n".join(out)


def write_report(res: dict, path: Path) -> None:
    b = res["benchmark"]
    L = [
        "# Experimental results (synthetic benchmark)",
        "",
        f"_Generated automatically by `python -m gridwatch.experiments.run` on {res['generated_at']} "
        f"(total {res['total_seconds']:.0f} s). Do not edit by hand._",
        "",
        "> **Scope.** Every number below is performance on the documented *synthetic* benchmark generated by this "
        "project. None of it is a measurement of real-world electricity-theft detection accuracy.",
        "",
        "## Setup",
        "",
        f"* Train runs: seeds {b['train_seeds'][0]}–{b['train_seeds'][1]} ({b['train_seeds'][2]} runs); validation "
        f"(threshold selection): {b['val_seeds'][0]}–{b['val_seeds'][1]} ({b['val_seeds'][2]}); test: "
        f"{b['test_seeds'][0]}–{b['test_seeds'][1]} ({b['test_seeds'][2]}). Splits are grouped by run (no run appears "
        "in two splits).",
        f"* Unit of evaluation: {b['unit_of_evaluation']}.",
        "* Test windows: " + "; ".join(f"{k}: {v['windows']} windows, {v['positives']} positive"
                                        for k, v in b["test_counts"].items()) + ".",
        "* Rules use their configured thresholds (score 1.0); ML methods use the threshold that maximised F1 on the "
        "validation runs. Isolation Forest is trained without labels; only its threshold uses validation labels.",
        "* 95 % confidence intervals: cluster bootstrap over test runs (300 resamples).",
        "",
        "## 1. Consumer-level detection (which consumer meter to examine)",
        "",
        _main_table(res["main"]["consumer"]),
        "",
        "The feeder energy-balance rule assigns its feeder score to every consumer on the feeder, so it cannot "
        "localise inside a feeder; its consumer-level precision shows that limitation.",
        "",
        "## 2. Feeder-level detection",
        "",
        _main_table(res["main"]["feeder"]),
        "",
        "## 3. DT-level detection",
        "",
        _main_table(res["main"]["dt"]),
        "",
        "## 3b. Paired comparisons (A minus B on identical test windows, cluster bootstrap)",
        "",
        "| Level | A | B | ΔF1 [95% CI] | P(ΔF1 ≤ 0) | ΔPR-AUC [95% CI] | P(ΔPR-AUC ≤ 0) |",
        "|---|---|---|---|---|---|---|",
        *[f"| {p['level']} | {p['a']} | {p['b']} | {_f(p['delta_f1'])} [{_f(p['delta_f1_ci95'][0])}, "
          f"{_f(p['delta_f1_ci95'][1])}] | {_f(p['p_f1_le_0'])} | {_f(p['delta_pr_auc'])} [{_f(p['delta_pr_auc_ci95'][0])}, "
          f"{_f(p['delta_pr_auc_ci95'][1])}] | {_f(p['p_pr_auc_le_0'])} |" for p in res.get("paired_comparisons", [])],
        "",
        "## 4. Rules with thresholds tuned on validation (fairness check)",
        "",
        _main_table(res["rules_tuned_on_validation"]["consumer"] + res["rules_tuned_on_validation"]["feeder"]),
        "",
        "## 5. Benign confounders (consumer level, flag rates among negative windows)",
        "",
        "| Method | Genuine consumption drop | Data fault (missing/delayed) | Other negatives | Recall (theft-like) |",
        "|---|---|---|---|---|",
    ]
    for r in res["confounders"]:
        L.append(f"| {r['name']} | {_f(r['flag_rate_benign_change'])} (n={r['n_benign']}) | "
                 f"{_f(r['flag_rate_data_fault'])} (n={r['n_fault']}) | {_f(r['flag_rate_other_negatives'], 4)} | "
                 f"{_f(r['recall_theft_like'])} |")
    sw = res["sweeps"]
    sweep_titles = (("prevalence", "Anomaly prevalence (share of consumers with recorded-consumption anomalies)"),
                    ("noise", "Meter-noise multiplier"), ("missing", "Base missing-reading rate"),
                    ("loss_error", "Persistent technical-loss estimate error on every feeder (%), with loss calibration"),
                    ("loss_error_uncalibrated", "Same loss-estimate error, loss calibration switched off (ablation)"))
    for i, (key, title) in enumerate(sweep_titles):
        if key not in sw:
            continue
        L += ["", f"## 6.{i + 1} Sweep: {title}", "",
              "Consumer level, F1:", "", _sweep_table(sw[key], "consumer", "f1"), "",
              "Consumer level, PR-AUC:", "", _sweep_table(sw[key], "consumer", "pr_auc"), "",
              "Feeder level, F1:", "", _sweep_table(sw[key], "feeder", "f1"), "",
              "Feeder level, false-positive rate:", "", _sweep_table(sw[key], "feeder", "fpr")]
    loc = res["localisation"]
    L += ["", "## 7. Localisation (single-feeder theft runs)", "", loc["definition"] + ".", "",
          "| Method | Feeder top-1 hit rate | DT top-1 hit rate |", "|---|---|---|"]
    for m in loc["results"]["feeder"]:
        L.append(f"| {m} | {_f(loc['results']['feeder'][m]['top1_hit_rate'])} | "
                 f"{_f(loc['results']['dt'][m]['top1_hit_rate'])} |")
    dl = res["delay"]
    L += ["", "## 8. Detection delay", "", dl["definition"], "",
          "| Level:method | Events | Detection rate | Median delay (h) | IQR (h) |", "|---|---|---|---|---|"]
    for k, v in dl["results"].items():
        L.append(f"| {k} | {v['events']} | {_f(v['detection_rate'])} | {_f(v['median_delay_h'], 0)} | "
                 f"{_f(v['p25_delay_h'], 0)}–{_f(v['p75_delay_h'], 0)} |")
    eb = res["energy_balance_recovery"]
    L += ["", "## 9. Energy-balance validation: recovery of injected unmetered energy", "", eb["definition"], "",
          "| Quantity | Mean | SD |", "|---|---|---|"]
    for k, v in eb["summary"].items():
        L.append(f"| {k} | {_f(v['mean'])} | {_f(v['sd'])} |")
    L += ["", "## 10. Runtime scaling", "",
          "| Consumers | DTs | Readings generated | Generation + feeder power flow (s) | Features per step (ms) | "
          "Scoring per step (ms) |", "|---|---|---|---|---|---|"]
    for r in res["runtime"]:
        L.append(f"| {r['consumers']} | {r['dts']} | {r['readings_generated']:,} | {r['generation_and_power_flow_s']} | "
                 f"{r['features_per_step_ms']} | {r['scoring_per_step_ms']} |")
    L += ["", "## 11. Most important features (Random Forest, consumer + grid)", "", "| Feature | Importance |",
          "|---|---|"]
    for r in res["rf_combined_importance"][:12]:
        L.append(f"| {r['feature']} | {_f(r['importance'])} |")
    L += ["", f"_Environment: Python {res['environment']['python']}, scikit-learn {res['environment']['sklearn']}, "
              f"{res['environment']['platform']}._", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L), encoding="utf-8")
